#!/bin/sh
set -euo pipefail

SECRETS_FILE="${CI_WORKSPACE:-$(pwd)}/Loam/Config/Secrets.xcconfig"

{
  echo "// Generated by ci_post_clone.sh for Xcode Cloud."

  if [ -n "${CI_BUILD_NUMBER:-}" ]; then
    echo "CURRENT_PROJECT_VERSION = ${CI_BUILD_NUMBER}"
  fi

  if [ -n "${SUPABASE_URL:-}" ] && [ -n "${SUPABASE_ANON_KEY:-}" ]; then
    xcconfig_url="${SUPABASE_URL//:\/\//:\/\$()\/}"
    echo "SUPABASE_URL = ${xcconfig_url}"
    echo "SUPABASE_ANON_KEY = ${SUPABASE_ANON_KEY}"
  else
    echo "warning: SUPABASE_URL and/or SUPABASE_ANON_KEY not set — using placeholder config (demo mode)." >&2
  fi
} > "$SECRETS_FILE"

echo "Wrote ${SECRETS_FILE} (build ${CI_BUILD_NUMBER:-local})."
